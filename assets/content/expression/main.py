"""Expression plotter: your own functions, with a slider for every parameter.

Generated by Formula from the rows of an Expression plotter. Explicit rows are
y = f(x), polar rows are r = f(theta), parametric rows are (x(t), y(t)). The
parts between the @ markers are what changes from one export to the next.
Drag the sliders to change the parameters; the curves redraw live.

Requirements: pip install numpy matplotlib
Run:          python main.py
"""
import numpy as np
import matplotlib.pyplot as plt
from matplotlib.animation import FuncAnimation
from matplotlib.widgets import Slider

np.seterr(all="ignore")              # sqrt(-1) and 1/0 just leave gaps
VIEW = (-4.0, 4.0, -3.0, 3.0)        # x min, x max, y min, y max
COLORS = ["#2346a0", "#23786e", "#a8700f"]
SAMPLES = 721

# name: (value, min, max)
PARAMS = {
# @PARAMS
    "a": (2.0, -10.0, 10.0),
    "b": (1.0, -10.0, 10.0),
    "k": (3.0, -10.0, 10.0),
# @END
}


def full(v, like):
    """One value per sample, even for a constant row like y = 2."""
    return np.broadcast_to(np.asarray(v, dtype=float), like.shape)


def explicit(f, xs):
    return xs, full(f(xs), xs)


def polar(f, t0, t1):
    theta = np.linspace(t0, t1, SAMPLES)
    r = full(f(theta), theta)
    return r * np.cos(theta), r * np.sin(theta)


def parametric(fx, fy, t0, t1):
    t = np.linspace(t0, t1, SAMPLES)
    return full(fx(t), t), full(fy(t), t)


def curves(p, xs):
    """Every row as an (x, y) pair of arrays; xs spans the view."""
# @EXPRESSIONS
    a, b, k = p["a"], p["b"], p["k"]

    def row1(x):
        return a * np.sin(b * x)

    def row2(theta):
        return 1 + np.cos(k * theta)

    return [explicit(row1, xs), polar(row2, 0.0, 6.283185307179586)]
# @END


def broken(xs, ys):
    """NaN where the curve jumps by more than five view heights, so the line
    is not drawn across an asymptote such as the ones of tan(x)."""
    xs, ys = np.array(xs, dtype=float), np.array(ys, dtype=float)
    span = VIEW[3] - VIEW[2]
    jump = np.zeros(len(ys), dtype=bool)
    jump[1:] = np.abs(np.diff(ys)) > 5 * span
    ys[jump | (np.abs(ys) > 1e6)] = np.nan
    return xs, ys


n_params = len(PARAMS)
fig = plt.figure(figsize=(7, 6 + 0.35 * n_params))
bottom = 0.08 + 0.045 * n_params
ax = fig.add_axes([0.1, bottom, 0.85, 0.95 - bottom])
ax.set_xlim(VIEW[0], VIEW[1])
ax.set_ylim(VIEW[2], VIEW[3])
ax.set_aspect("equal")
ax.grid(True, color="0.9")
ax.axhline(0, color="0.5", lw=1)
ax.axvline(0, color="0.5", lw=1)

sliders = {}
for i, (name, (value, lo, hi)) in enumerate(PARAMS.items()):
    slot = fig.add_axes([0.2, 0.03 + 0.045 * i, 0.6, 0.025])
    sliders[name] = Slider(slot, name, lo, hi, valinit=value)


def values():
    return {name: s.val for name, s in sliders.items()}


xs = np.linspace(VIEW[0], VIEW[1], 1601)
lines = [
    ax.plot([], [], color=COLORS[i % 3], lw=2, ls="--" if i >= 3 else "-")[0]
    for i in range(len(curves(values(), xs)))
]


def update(_frame):
    for line, (cx, cy) in zip(lines, curves(values(), xs)):
        line.set_data(*broken(cx, cy))
    return lines


anim = FuncAnimation(fig, update, interval=50, cache_frame_data=False)
plt.show()
